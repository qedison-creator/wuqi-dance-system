"use strict";

var _async_generator = require("./_async_generator.js");

function _wrap_async_generator(fn) {
    return function() {
        return new _async_generator._(fn.apply(this, arguments));
    };
}
exports._ = _wrap_async_generator;

// ===== swc-runtime compat（由 gen-swc-runtime.js 追加）=====
(function () {
  try {
    var keys = Object.keys(module.exports);
    var main = null;
    for (var i = 0; i < keys.length; i++) {
      if (typeof module.exports[keys[i]] === 'function') { main = module.exports[keys[i]]; break; }
    }
    if (typeof main !== 'function' || typeof module.exports === 'function') return;
    main['_wrap_async_generator'] = main;
    main._ = main;
    main.default = main;
    module.exports = main;
  } catch (e) { /* 保持原导出 */ }
})();
